import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { chmodSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, test } from "node:test";
import { hookRunnerProblems } from "../src/hookrunners.ts";
import { initCommittedRepo } from "./helpers.ts";

const base = realpathSync(mkdtempSync(join(tmpdir(), "aos-hookrunners-")));
after(() => rmSync(base, { recursive: true, force: true }));

let counter = 0;

function project(hooksPath?: string) {
  const root = initCommittedRepo(join(base, `repo-${counter++}`));
  if (hooksPath !== undefined) execFileSync("git", ["-C", root, "config", "core.hooksPath", hooksPath]);
  const sessionHooksDir = join(root, ".git", "hooks");
  const problems = (): string[] => hookRunnerProblems({ commonDir: join(root, ".git"), worktreePath: root, sessionHooksDir });
  const hook = (dir: string, name: string, text: string): void => {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, name), text);
    chmodSync(join(dir, name), 0o755);
  };
  return { root, sessionHooksDir, problems, hook };
}

const PRE_COMMIT_SHIM = `#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
INSTALL_PYTHON=/opt/homebrew/opt/python@3.12/bin/python3.12
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit)
if [ -x "$INSTALL_PYTHON" ]; then exec "$INSTALL_PYTHON" -mpre_commit "\${ARGS[@]}"
elif command -v pre-commit > /dev/null; then exec pre-commit "\${ARGS[@]}"
else echo '\`pre-commit\` not found.' 1>&2; exit 1; fi
`;

describe("hookRunnerProblems", () => {
  test("a pre-commit hook that bakes in a Mac interpreter is fine, because the image ships pre-commit", () => {
    const p = project();
    p.hook(p.sessionHooksDir, "pre-commit", PRE_COMMIT_SHIM);
    assert.deepEqual(p.problems(), []);
  });

  test("lefthook hooks need node_modules in the worktree", () => {
    const p = project();
    p.hook(p.sessionHooksDir, "pre-commit", '#!/bin/sh\ncall_lefthook run "pre-commit" "$@"\n# lefthook\n');
    assert.match(p.problems().join("\n"), /run lefthook.*npm install/);
    mkdirSync(join(p.root, "node_modules", ".bin"), { recursive: true });
    writeFileSync(join(p.root, "node_modules", ".bin", "lefthook"), "");
    assert.deepEqual(p.problems(), []);
  });

  test("husky's hooks directory is created by the package install", () => {
    const p = project(".husky/_");
    assert.match(p.problems().join("\n"), /husky creates during `npm install`/);
    p.hook(join(p.root, ".husky", "_"), "pre-commit", "#!/usr/bin/env sh\n. \"$(dirname \"$0\")/h\"\n");
    assert.deepEqual(p.problems(), []);
  });

  test("an in-tree custom hooks directory is checked like the installed hooks", () => {
    const p = project(".githooks");
    p.hook(join(p.root, ".githooks"), "pre-commit", "#!/opt/homebrew/bin/bash\nexit 0\n");
    assert.match(p.problems().join("\n"), /hook pre-commit starts with \/opt\/homebrew\/bin\/bash/);
  });

  test("a hooks path outside the project cannot be seen by the container", () => {
    const p = project("/Users/someone/hooks");
    assert.match(p.problems().join("\n"), /outside the project/);
  });

  test("a hooks path that climbs out of the project is outside it too", () => {
    const p = project("../shared-hooks");
    assert.match(p.problems().join("\n"), /outside the project/);
  });

  test("portable hooks report nothing", () => {
    const p = project(".githooks");
    p.hook(join(p.root, ".githooks"), "pre-commit", "#!/usr/bin/env bash\nexit 0\n");
    assert.deepEqual(p.problems(), []);
  });
});
